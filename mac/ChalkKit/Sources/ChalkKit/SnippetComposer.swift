import Foundation

/// Generates the hsnips content sent to the editor: the bundled defaults, then
/// the user's shortcuts and a `# chalk-disable:` line (a comment to any other
/// hsnips consumer).
public enum SnippetComposer {
    /// Priority emitted before every user snippet. Built-ins are priority 0
    /// and the parser resets priority after each snippet, so the line must
    /// be repeated per snippet for user shortcuts to shadow built-ins.
    static let userPriority = 10

    public static func compose(
        base: String,
        user: [UserSnippet],
        disabledBuiltins: Set<String>
    ) -> String {
        let active = user.filter { $0.enabled }
        // Fork keys come from every user snippet, enabled or not: a disabled
        // fork means that row is off, which must not resurrect the built-in.
        var disableKeys = disabledBuiltins
        for snippet in user {
            if let key = snippet.overridesBuiltinKey { disableKeys.insert(key) }
        }
        // Never emit a key that names a snippet we are also emitting: the
        // parser matches on trigger and would disable the override too. The
        // built-in stays, shadowed by priority, but still fires where the
        // user snippet's `context` excludes it.
        disableKeys.subtract(active.map(\.trigger))
        if active.isEmpty && disableKeys.isEmpty { return base }

        var out = base
        if !out.hasSuffix("\n") { out += "\n" }
        out += "\n# ── Chalk user shortcuts (generated by Settings — do not hand-edit) ──\n"

        if !disableKeys.isEmpty {
            let keys = disableKeys.sorted().map(quoteDisableKey)
            out += "# chalk-disable: \(keys.joined(separator: " "))\n"
        }

        for snippet in active {
            // hsnips has no escaping, so `"` is stripped from the description.
            // An empty description would make the header lose its flags, so
            // an all-quotes trigger gets a stand-in.
            let stripped = snippet.trigger.replacingOccurrences(of: "\"", with: "")
            let description = stripped.isEmpty ? "shortcut" : stripped
            let trigger = snippet.options.isRegex ? "`\(snippet.trigger)`" : snippet.trigger
            out += "\npriority \(userPriority)\n"
            if let context = snippet.options.contextFilter {
                out += "context \(context)\n"
            }
            out += "snippet \(trigger) \"\(description)\" \(snippet.options.flagString)\n"
            out += snippet.replacement + "\n"
            out += "endsnippet\n"
        }
        return out
    }

    /// Backtick-quote keys containing whitespace so the directive tokenizer
    /// reads them as one key.
    private static func quoteDisableKey(_ key: String) -> String {
        key.contains(where: { $0 == " " || $0 == "\t" }) ? "`\(key)`" : key
    }

    // ── Validation (hsnips has no escaping — reject what would break) ──

    /// Returns a user-facing error, or nil when the trigger is valid.
    /// Backticks are banned either way: they delimit the regex form.
    public static func validateTrigger(_ trigger: String, isRegex: Bool = false) -> String? {
        if trigger.isEmpty { return "Trigger can't be empty." }
        if trigger.count > 64 { return "Trigger is too long (max 64 characters)." }
        if trigger.contains("`") { return "Trigger can't contain backticks." }
        if trigger.contains(where: { $0.isNewline }) {
            return "Trigger can't contain line breaks."
        }
        if isRegex {
            // ICU here, JS in the editor — this catches most mistakes, and
            // the parser skips anything only JS rejects.
            if (try? NSRegularExpression(pattern: trigger)) == nil {
                return "That isn't a valid pattern."
            }
            return nil
        }
        if trigger.contains(where: { $0.isWhitespace }) {
            return "Trigger can't contain spaces."
        }
        return nil
    }

    /// Returns a user-facing error, or nil when the replacement is valid.
    public static func validateReplacement(_ replacement: String) -> String? {
        if replacement.isEmpty { return "Replacement can't be empty." }
        // `endsnippet` at line start terminates the body in the parser.
        for line in replacement.components(separatedBy: .newlines)
        where line.hasPrefix("endsnippet") {
            return "Replacement lines can't start with “endsnippet”."
        }
        // `` opens an inline JS block; the parser strips everything inside.
        if replacement.contains("``") {
            return "Replacement can't contain double backticks (``)."
        }
        return nil
    }
}
