import XCTest
@testable import ChalkKit

/// Pins `SnippetComposer.compose` output byte for byte.
///
/// The same literal appears in
/// `packages/editor-core/test/hsnips-composer-parity.test.ts`, which feeds it
/// through `parseHSnips` and asserts the flags come back out. The two sides
/// are separate implementations of one wire format (Swift writes, TypeScript
/// reads), so nothing but a shared fixture proves they agree. If this test
/// fails because the composer changed on purpose, copy the new expected
/// string into that TypeScript test as well.
final class SnippetComposerParityTests: XCTestCase {
    /// Exercises the whole header grammar in one file: a backtick-quoted
    /// regex trigger whose description is the regex source, `w`+`b` together,
    /// an inverted context, a context-free snippet, per-snippet `priority`,
    /// and a `# chalk-disable:` key that contains a space.
    static let base = #"""
    snippet ;; "Inline math" iA
    \$$0\$
    endsnippet

    snippet te "text" A
    \text{$0}
    endsnippet

    snippet `([a-z]) bar` "spaced regex" A
    \bar{#1}
    endsnippet

    """#

    static let user = [
        // Regex fork of the spaced-source built-in: its override key is what
        // puts a backtick-quoted, space-carrying key on the disable line.
        UserSnippet(
            id: "u1",
            trigger: "([a-z])bar",
            replacement: #"\bar{#1}"#,
            options: SnippetOptions(
                mode: .math, autoExpand: true, wholeWord: true,
                lineStart: true, isRegex: true),
            overridesBuiltinKey: "([a-z]) bar"
        ),
        UserSnippet(
            id: "u2",
            trigger: ";t",
            replacement: #"\text{$0}"#,
            options: SnippetOptions(mode: .text)
        ),
        UserSnippet(
            id: "u3",
            trigger: ";q",
            replacement: #"\quad"#,
            options: SnippetOptions(mode: .any, autoExpand: false)
        ),
    ]

    static let disabledBuiltins: Set<String> = ["te"]

    /// Byte-for-byte what the composer emits for the inputs above. Blank
    /// lines included: the parser skips them, but a fixture that drops them
    /// would stop being a literal copy.
    static let expected = #"""
    snippet ;; "Inline math" iA
    \$$0\$
    endsnippet

    snippet te "text" A
    \text{$0}
    endsnippet

    snippet `([a-z]) bar` "spaced regex" A
    \bar{#1}
    endsnippet

    # ── Chalk user shortcuts (generated by Settings — do not hand-edit) ──
    # chalk-disable: `([a-z]) bar` te

    priority 10
    context math(context)
    snippet `([a-z])bar` "([a-z])bar" Awb
    \bar{#1}
    endsnippet

    priority 10
    context !math(context)
    snippet ;t ";t" Ai
    \text{$0}
    endsnippet

    priority 10
    snippet ;q ";q" i
    \quad
    endsnippet

    """#

    func testComposerOutputMatchesTheSharedFixture() {
        XCTAssertEqual(
            SnippetComposer.compose(
                base: Self.base, user: Self.user,
                disabledBuiltins: Self.disabledBuiltins),
            Self.expected
        )
    }
}
