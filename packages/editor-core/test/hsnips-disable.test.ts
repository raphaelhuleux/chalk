import { describe, it, expect, beforeAll } from 'vitest';
import { EditorView } from '@codemirror/view';
import { EditorState, EditorSelection } from '@codemirror/state';
import { parseHSnips } from '../src/editor/hsnips-parser';
import {
  hsnipsExtension,
  setSnippets as setSnippetsEffect,
  _testing,
} from '../src/editor/hsnips-plugin';

const { findMatch, manualExpand } = _testing;

beforeAll(() => {
  if (typeof Range.prototype.getClientRects !== 'function') {
    Range.prototype.getClientRects = () => [] as unknown as DOMRectList;
  }
  if (typeof Range.prototype.getBoundingClientRect !== 'function') {
    Range.prototype.getBoundingClientRect = () =>
      ({ x: 0, y: 0, width: 0, height: 0, top: 0, right: 0, bottom: 0, left: 0, toJSON: () => ({}) }) as DOMRect;
  }
});

const BASE = `
snippet ;; "Inline math" iA
\\$$0\\$
endsnippet

snippet te "text" A
\\text{$0}
endsnippet

snippet \`([ ]*)sr\` "squared" A
^2
endsnippet
`;

describe('# chalk-disable directive', () => {
  it('removes a plain-trigger snippet named anywhere in the file', () => {
    const content = BASE + '\n# chalk-disable: te\n';
    const triggers = parseHSnips(content).map((s) => s.trigger);
    expect(triggers).not.toContain('te');
    expect(triggers).toContain(';;');
  });

  it('removes a regex snippet by backtick-quoted raw source', () => {
    const content = BASE + '\n# chalk-disable: `([ ]*)sr`\n';
    const parsed = parseHSnips(content);
    expect(parsed.some((s) => s.regexpSource === '([ ]*)sr')).toBe(false);
    expect(parsed.map((s) => s.trigger)).toContain('te');
  });

  it('accepts multiple keys on one line and ignores unknown keys', () => {
    const content = BASE + '\n# chalk-disable: te nosuchkey `([ ]*)sr`\n';
    const parsed = parseHSnips(content);
    expect(parsed.length).toBe(1);
    expect(parsed[0].trigger).toBe(';;');
  });

  it('is order-independent (directive before the snippets it disables)', () => {
    const content = '# chalk-disable: te\n' + BASE;
    expect(parseHSnips(content).map((s) => s.trigger)).not.toContain('te');
  });

  it('leaves ordinary comments alone', () => {
    const content = BASE + '\n# chalk-disable is documented here, not invoked\n';
    // No colon after "chalk-disable" — must not disable anything.
    expect(parseHSnips(content).length).toBe(3);
  });
});

describe('a fork that keeps its built-in trigger', () => {
  // What SnippetComposer emits when Settings edits only the replacement of
  // the built-in `;;`: the fork's disable key would equal its own trigger.
  // The directive matches on trigger, so emitting it deletes the override
  // together with the built-in and the shortcut stops firing. Swift pins the
  // no-key side in `SnippetComposerTests.testSameTriggerForkDoesNotDisableItself`.
  const composed =
    BASE +
    `
# ── Chalk user shortcuts (generated by Settings — do not hand-edit) ──

priority 10
context math(context)
snippet ;; ";;" Ai
^{$0}
endsnippet
`;

  it('survives parsing and keeps the user body', () => {
    const parsed = parseHSnips(composed);
    const own = parsed.filter((s) => s.trigger === ';;');
    expect(own.length).toBe(2);
    expect(parsed[0].priority).toBe(10);
    expect(parsed[0].body).toBe('^{$0}');
  });

  it('wins over the built-in at the cursor', () => {
    const state = EditorState.create({
      doc: 'x;;',
      selection: EditorSelection.cursor(3),
    });
    const match = findMatch(state, parseHSnips(composed), () => true);
    expect(match).not.toBeNull();
    expect(match!.snippet.body).toBe('^{$0}');
  });

  it('is erased along with the built-in if the key is emitted', () => {
    // The bug this guards: one directive line, both snippets gone.
    const withKey = composed.replace(
      '# ── Chalk user shortcuts (generated by Settings — do not hand-edit) ──',
      '# chalk-disable: ;;',
    );
    expect(parseHSnips(withKey).some((s) => s.trigger === ';;')).toBe(false);
  });
});

describe('user snippets shadow built-ins via priority', () => {
  const composed =
    BASE +
    `
# ── Chalk user shortcuts ──
priority 10
snippet te "te" Ai
\\top
endsnippet
`;

  it('parses the user snippet at priority 10, sorted first', () => {
    const parsed = parseHSnips(composed);
    const te = parsed.filter((s) => s.trigger === 'te');
    expect(te.length).toBe(2);
    expect(parsed[0].priority).toBe(10);
    expect(parsed[0].body).toBe('\\top');
  });

  it('findMatch picks the user snippet over the built-in', () => {
    const state = EditorState.create({
      doc: 'te',
      selection: EditorSelection.cursor(2),
    });
    const match = findMatch(state, parseHSnips(composed), () => true);
    expect(match).not.toBeNull();
    expect(match!.snippet.body).toBe('\\top');
  });
});

describe('manual Tab expansion of non-automatic snippets', () => {
  const NON_AUTO = `
snippet frac "fraction"
\\frac{$1}{$2}
endsnippet
`;

  function makeView(doc: string, cursor: number): EditorView {
    const state = EditorState.create({
      doc,
      selection: EditorSelection.cursor(cursor),
      extensions: [hsnipsExtension({ isInMathContext: () => true })],
    });
    const view = new EditorView({ state });
    view.dispatch({ effects: setSnippetsEffect.of(parseHSnips(NON_AUTO)) });
    return view;
  }

  it('auto-expand ignores flagless snippets', () => {
    const parsed = parseHSnips(NON_AUTO);
    const state = EditorState.create({
      doc: 'frac',
      selection: EditorSelection.cursor(4),
    });
    expect(findMatch(state, parsed, () => true)).toBeNull();
  });

  it('manualExpand expands a flagless snippet at the cursor', () => {
    const view = makeView('frac', 4);
    expect(manualExpand(view)).toBe(true);
    expect(view.state.doc.toString()).toBe('\\frac{}{}');
    view.destroy();
  });

  it('manualExpand returns false when nothing matches (Tab falls through)', () => {
    const view = makeView('nope', 4);
    expect(manualExpand(view)).toBe(false);
    expect(view.state.doc.toString()).toBe('nope');
    view.destroy();
  });
});
