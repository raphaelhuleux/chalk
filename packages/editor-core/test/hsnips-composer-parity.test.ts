import { describe, it, expect } from 'vitest';
import { parseHSnips } from '../src/editor/hsnips-parser';

/**
 * Swift writes this wire format, TypeScript reads it, and they are separate
 * implementations — the branch's named architectural risk. The fixture below
 * is a literal copy of what
 * `SnippetComposer.compose` (mac/ChalkKit/Sources/ChalkKit/SnippetComposer.swift)
 * emits, one array entry per emitted line, blank lines included; the only
 * change is JavaScript's own backslash escaping. The identical string is
 * pinned on the Swift side by
 * `SnippetComposerParityTests.testComposerOutputMatchesTheSharedFixture`
 * (mac/ChalkKit/Tests/ChalkKitTests/SnippetComposerParityTests.swift), which
 * fails the moment the composer's bytes drift from this copy. Change one
 * side, change both.
 *
 * Composer inputs, for reference: the three base snippets below, three user
 * snippets (a regex fork with `w`+`b`, a text-mode one, a context-free
 * manual one), and `disabledBuiltins = ["te"]`. The fork's
 * `overridesBuiltinKey` is `([a-z]) bar`, which is what puts a
 * space-carrying, backtick-quoted key on the `# chalk-disable:` line.
 */
const COMPOSED = [
  'snippet ;; "Inline math" iA',
  '\\$$0\\$',
  'endsnippet',
  '',
  'snippet te "text" A',
  '\\text{$0}',
  'endsnippet',
  '',
  'snippet `([a-z]) bar` "spaced regex" A',
  '\\bar{#1}',
  'endsnippet',
  '',
  '# ── Chalk user shortcuts (generated by Settings — do not hand-edit) ──',
  '# chalk-disable: `([a-z]) bar` te',
  '',
  'priority 10',
  'context math(context)',
  'snippet `([a-z])bar` "([a-z])bar" Awb',
  '\\bar{#1}',
  'endsnippet',
  '',
  'priority 10',
  'context !math(context)',
  'snippet ;t ";t" Ai',
  '\\text{$0}',
  'endsnippet',
  '',
  'priority 10',
  'snippet ;q ";q" i',
  '\\quad',
  'endsnippet',
  '',
].join('\n');

describe('composer output parses back to the intended flags', () => {
  const parsed = parseHSnips(COMPOSED);
  const byRegex = (source: string) => parsed.find((s) => s.regexpSource === source);
  const byTrigger = (trigger: string) => parsed.find((s) => s.trigger === trigger);

  it('keeps exactly the snippets the disable line did not name', () => {
    // Three user snippets plus the one base snippet neither key disables.
    expect(parsed.length).toBe(4);
  });

  it('honours a backtick-quoted disable key containing a space', () => {
    // `([a-z]) bar` has to survive the directive tokenizer as one key.
    expect(byRegex('([a-z]) bar')).toBeUndefined();
    expect(byTrigger('te')).toBeUndefined();
    expect(byTrigger(';;')).toBeDefined();
  });

  it('reads a regex trigger, its description, and the w+b flag group', () => {
    // HEADER_RE's optional description and flag groups both have to match
    // after the backtick group: `snippet `pat` "desc" Awb`.
    const snippet = byRegex('([a-z])bar');
    expect(snippet).toBeDefined();
    expect(snippet!.trigger).toBe('');
    expect(snippet!.regexpSource).toBe('([a-z])bar');
    // The composer writes the regex source as the description too.
    expect(snippet!.description).toBe('([a-z])bar');
    // Wrapped, not suffixed: see the anchoring tests in
    // hsnips-parser-resilience.test.ts for why `pat + '$'` was unsafe.
    expect(snippet!.regexp?.source).toBe('(?:([a-z])bar)$');
    expect(snippet!.automatic).toBe(true);
    expect(snippet!.inword).toBe(false);
    expect(snippet!.wordboundary).toBe(true);
    expect(snippet!.beginofline).toBe(true);
    expect(snippet!.contextFilter).toBe('math(context)');
    expect(snippet!.priority).toBe(10);
    expect(snippet!.body).toBe('\\bar{#1}');
  });

  it('reads text mode as the inverted context filter', () => {
    const snippet = byTrigger(';t');
    expect(snippet).toBeDefined();
    expect(snippet!.contextFilter).toBe('!math(context)');
    expect(snippet!.regexpSource).toBeUndefined();
    expect(snippet!.description).toBe(';t');
    expect(snippet!.automatic).toBe(true);
    expect(snippet!.inword).toBe(true);
    expect(snippet!.wordboundary).toBe(false);
    expect(snippet!.beginofline).toBe(false);
    expect(snippet!.priority).toBe(10);
    expect(snippet!.body).toBe('\\text{$0}');
  });

  it('leaves a mode-any, manual snippet with no context and no A flag', () => {
    const snippet = byTrigger(';q');
    expect(snippet).toBeDefined();
    // Proves the parser reset `context` after the previous snippet — the
    // composer emits no context line here, so a leak would show as
    // `!math(context)`.
    expect(snippet!.contextFilter).toBeUndefined();
    expect(snippet!.automatic).toBe(false);
    expect(snippet!.inword).toBe(true);
    expect(snippet!.wordboundary).toBe(false);
    expect(snippet!.beginofline).toBe(false);
    expect(snippet!.priority).toBe(10);
  });

  it('gives every user snippet priority 10 and leaves the built-in at 0', () => {
    // The composer repeats `priority 10` per snippet because the parser
    // resets it after each one; all three user snippets sort ahead.
    expect(parsed.slice(0, 3).map((s) => s.priority)).toEqual([10, 10, 10]);
    expect(byTrigger(';;')!.priority).toBe(0);
    expect(byTrigger(';;')!.contextFilter).toBeUndefined();
  });
});
