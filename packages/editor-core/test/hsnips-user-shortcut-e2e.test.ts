import { describe, it, expect, beforeEach, beforeAll } from 'vitest';
import { mockPort } from './helpers/views';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { EditorView } from '@codemirror/view';
import { EditorSelection } from '@codemirror/state';
import { mountEditor } from '../src/index';

/**
 * End-to-end cover for a Settings-authored shortcut: the REAL bundled
 * defaults, composed the way `SnippetComposer` composes them, pushed over the
 * real `HostPort` into a real mounted editor, expanded by real keystrokes.
 *
 * The unit tests either side of this seam both passed while the feature was
 * broken end to end (a `# chalk-disable:` key that matched the override's own
 * trigger deleted it), so the seam gets its own test.
 */
const BUNDLED = readFileSync(join(__dirname, '../assets/latex.hsnips'), 'utf8');

/** Mirrors SnippetComposer.compose for one enabled math-mode shortcut. */
function composeUserShortcut(trigger: string, replacement: string): string {
  return (
    BUNDLED +
    '\n# ── Chalk user shortcuts (generated by Settings — do not hand-edit) ──\n' +
    `\npriority 10\ncontext math(context)\n` +
    `snippet ${trigger} "${trigger}" Ai\n${replacement}\nendsnippet\n`
  );
}

beforeAll(() => {
  if (typeof Range.prototype.getClientRects !== 'function') {
    Range.prototype.getClientRects = () => [] as unknown as DOMRectList;
  }
  if (typeof Range.prototype.getBoundingClientRect !== 'function') {
    Range.prototype.getBoundingClientRect = () =>
      ({ x: 0, y: 0, width: 0, height: 0, top: 0, right: 0, bottom: 0, left: 0, toJSON: () => ({}) }) as DOMRect;
  }
});

describe('a Settings-authored shortcut in a mounted editor', () => {
  let root: HTMLElement;

  beforeEach(() => {
    document.body.innerHTML = '';
    root = document.createElement('div');
    document.body.appendChild(root);
  });

  function mountWith(hsnips: string, text: string, cursor: number): EditorView {
    const mock = mockPort();
    mountEditor({ root, port: mock.port });
    mock.push({ type: 'init', text, language: 'tex' });
    mock.push({ type: 'hsnips', content: hsnips });
    const view = EditorView.findFromDOM(root)!;
    view.dispatch({ selection: EditorSelection.cursor(cursor) });
    return view;
  }

  /** One character, the way auto-expand recognises a keystroke. */
  function type(view: EditorView, ch: string) {
    const pos = view.state.selection.main.head;
    view.dispatch({
      changes: { from: pos, insert: ch },
      selection: EditorSelection.cursor(pos + 1),
      userEvent: 'input.type',
    });
  }

  it('expands inside math and leaves the caret on the $0 stop', () => {
    // `$x$` with the caret between `x` and the closing `$`.
    const view = mountWith(composeUserShortcut(';;', '^{$0}'), '$x$', 2);
    type(view, ';');
    type(view, ';');
    expect(view.state.doc.toString()).toBe('$x^{}$');
    // Between `{` (index 3) and `}` (index 4) — ready to type the exponent.
    expect(view.state.selection.main.head).toBe(4);
    view.destroy();
  });

  it('does not expand outside math, where its context filter excludes it', () => {
    const view = mountWith(composeUserShortcut(';;', '^{$0}'), 'plain ', 6);
    type(view, ';');
    type(view, ';');
    expect(view.state.doc.toString()).toBe('plain ;;');
    view.destroy();
  });

  it('does not expand inside \\text, through the real setup wiring', () => {
    // Proves setup.ts actually composes the \text exclusion into the hsnips
    // math filter; latex-text-span.test.ts only checks the predicate itself.
    // `nu` is a bundled Ai snippet, so this is the exact `$\text{number}$`
    // case: without the exclusion it expands two characters in.
    const view = mountWith(BUNDLED, '$\\text{}$', 7);
    type(view, 'n');
    type(view, 'u');
    expect(view.state.doc.toString()).toBe('$\\text{nu}$');
    view.destroy();
  });

  it('still expands the same trigger in real math', () => {
    const view = mountWith(BUNDLED, '$$', 1);
    type(view, 'n');
    type(view, 'u');
    expect(view.state.doc.toString()).toBe('$\\nu$');
    view.destroy();
  });

  it('wins over the built-in that shares its trigger', () => {
    // The built-in `;;` is still in the file (no disable key is emitted for a
    // same-trigger fork); priority 10 is the only thing keeping the user's
    // body in front of it.
    const view = mountWith(composeUserShortcut(';;', '\\qquad$0'), '$x$', 2);
    type(view, ';');
    type(view, ';');
    expect(view.state.doc.toString()).toBe('$x\\qquad$');
    view.destroy();
  });
});
