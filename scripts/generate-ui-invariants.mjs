#!/usr/bin/env node
/**
 * Renders ChromeInvariant.catalogue into docs/ui-invariants.md.
 *
 * The catalogue is the shared vocabulary between the owner and the tests: once
 * a rule has a name, a screenshot can be discussed by naming it rather than
 * describing the picture. This file makes the names readable without opening
 * Swift.
 *
 * The catalogue is Swift, so this parses the source rather than executing it
 * -- the generator runs without a build.
 *
 *   node scripts/generate-ui-invariants.mjs           # write the doc
 *   node scripts/generate-ui-invariants.mjs --check   # fail if it is stale
 *
 * --check is what scripts/check.sh runs. Without it the doc silently drifts
 * from the catalogue, and a generated document that reads as authoritative
 * while being wrong is worse than no document: it once claimed rules were
 * asserted in states where the suite skipped them.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const docPath = resolve(root, 'docs/ui-invariants.md');
const swiftPath = resolve(root, 'mac/ChalkKit/Sources/ChalkKit/ChromeInvariants.swift');
const src = readFileSync(swiftPath, 'utf8');
const check = process.argv.includes('--check');

const entries = [...src.matchAll(
  /name:\s*"([^"]+)",\s*\n\s*rationale:\s*"([^"]*)"/g)]
  .map(([, name, rationale]) => ({ name, rationale }));

if (entries.length < 6) {
  console.error(
    `only found ${entries.length} invariants (expected at least 6); ` +
    'did ChromeInvariants.swift change shape?');
  process.exit(1);
}

// The coverage section is prose about what the suite really asserts, and it
// lives in the Swift file so it sits next to the predicates it describes.
const coverage = src.match(
  /^\s*\/\/ COVERAGE-DOC-BEGIN\n([\s\S]*?)^\s*\/\/ COVERAGE-DOC-END$/m);
if (!coverage) {
  console.error(
    'no COVERAGE-DOC-BEGIN/END block in ChromeInvariants.swift; the generated ' +
    'doc must state what is and is not asserted, so this is ' +
    'not optional');
  process.exit(1);
}
const coverageText = coverage[1]
  .split('\n')
  .map(line => line.replace(/^\s*\/\/ ?/, ''))
  .join('\n')
  .trim();

const out = `# Chrome invariants

Generated by \`scripts/generate-ui-invariants.mjs\` from \`mac/ChalkKit/Sources/ChalkKit/ChromeInvariants.swift\`; do not edit by hand.
\`node scripts/generate-ui-invariants.mjs --check\` fails when this file and the Swift catalogue disagree, and \`scripts/check.sh\` runs it.

Naming one of these is enough to describe a chrome bug precisely.

${coverageText}

## The rules

${entries.map(e => `### \`${e.name}\`\n\n${e.rationale}\n`).join('\n')}
_${entries.length} invariants._
`;

if (check) {
  let current = null;
  try {
    current = readFileSync(docPath, 'utf8');
  } catch {
    console.error('docs/ui-invariants.md is missing; run node scripts/generate-ui-invariants.mjs');
    process.exit(1);
  }
  if (current !== out) {
    console.error(
      'docs/ui-invariants.md is stale: it does not match ChromeInvariants.swift.\n' +
      'Run: node scripts/generate-ui-invariants.mjs');
    process.exit(1);
  }
  console.log(`docs/ui-invariants.md is up to date (${entries.length} invariants)`);
} else {
  writeFileSync(docPath, out);
  console.log(`wrote docs/ui-invariants.md (${entries.length} invariants)`);
}
